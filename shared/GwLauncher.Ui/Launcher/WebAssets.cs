using System.Reflection;

namespace GwLauncher.Ui;

// The page, its stylesheet and script, and the helmet icon, all embedded in this assembly.
public static class WebAssets
{
    // Users restyle the launcher in GWLauncher.override.css beside the executable.
    public static string OverridePath => Path.Combine(AppContext.BaseDirectory, "GWLauncher.override.css");

    private static string BuiltInStylesPath => Path.Combine(AppContext.BaseDirectory, "GWLauncher.css");

    private const string BuiltInStylesHeader = """
        /*
         * GW Launcher's built-in styles, for reference.
         *
         * Do not edit this file. GW Launcher overwrites it every time it runs.
         * To change the styles, edit GWLauncher.override.css instead.
         */

        """;

    // index.html with the stylesheet and script inlined, so each platform loads one string with no file paths.
    // The override comes last, so its rules win over the built-in ones.
    public static string Page()
    {
        WriteBuiltInStyles();
        return Read("wwwroot/index.html")
            .Replace("<!-- styles -->", $"<style>{Read("wwwroot/app.css")}\n{Override()}</style>")
            .Replace("<!-- script -->", $"<script>{Read("wwwroot/app.js")}</script>");
    }

    // Writes the helmet icon to a file, for the window icon, the tray and desktop shortcuts.
    public static string SaveIcon(string path)
    {
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        using var source = Open("gwlauncher-helmet.png");
        using var target = File.Create(path);
        source.CopyTo(target);
        return path;
    }

    // The helmet as a data URL, so the account list can show it beside each account.
    public static string IconDataUrl()
    {
        using var source = Open("gwlauncher-helmet.png");
        using var buffer = new MemoryStream();
        source.CopyTo(buffer);
        return "data:image/png;base64," + Convert.ToBase64String(buffer.ToArray());
    }

    // Copies the built-in stylesheet beside the executable, for reference. The page itself always uses the embedded copy.
    private static void WriteBuiltInStyles()
    {
        try
        {
            File.WriteAllText(BuiltInStylesPath, BuiltInStylesHeader + Read("wwwroot/app.css"));
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
            // The reference copy is optional, so a failed write is ignored.
        }
    }

    // Creates the override file with its instructions the first time, then reads it. Without a readable file there are no overrides.
    private static string Override()
    {
        try
        {
            if (!File.Exists(OverridePath))
            {
                File.WriteAllText(OverridePath, OverrideTemplate);
            }

            return File.ReadAllText(OverridePath);
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
            return "";
        }
    }

    private const string OverrideTemplate = """
        /*
         * GW Launcher style overrides.
         *
         * Rules in this file are applied after the launcher's built-in styles, so they win over them.
         * Add your own rules below, for example:
         *
         *   ul.accounts li.selected { background: #ffe8b0; }
         *   :root { --accent: #c05621; }
         *
         * The built-in colours are CSS variables on :root: --accent, --border, --muted, --danger, --warning and --ok.
         * Clear this file to go back to the built-in styles. Changes apply the next time a launcher window opens.
         */

        """;

    private static string Read(string name)
    {
        using var reader = new StreamReader(Open(name));
        return reader.ReadToEnd();
    }

    private static Stream Open(string name) =>
        Assembly.GetExecutingAssembly().GetManifestResourceStream(name)
        ?? throw new InvalidOperationException($"The {name} resource is missing from GwLauncher.Ui.");
}
